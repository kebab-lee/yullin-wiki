// 지금은 읽기 하나뿐이다. **쓰기가 없는 것이 의도다** — 태그는 게시물을 저장할
// 때 함께 만들어지고(pageRepository 의 upsertTags), 태그만 따로 만들거나 이름을
// 고치는 문은 없다. 어드민 태그 관리 화면은 별도 과제이며, 그것이 생기기 전까지
// 태그 이름은 사실상 불변이다 — `/tags/[name]` 이 id 가 아니라 이름을 URL 로
// 쓸 수 있는 근거가 그것이다.
//
// HTTP 를 모른다. 다른 service 와 같다.
// =============================================================

import * as tagRepository from "@/lib/repositories/tagRepository";
import type { TagSummary } from "@/lib/types";

/**
 * 전체 태그 목록 (`/tags`). 공개 문서 수를 달아서 준다.
 *
 * **공개 문서가 0건인 태그는 뺀다.** 고아 태그가 실제로 생기는 구조이기 때문이다
 * — 게시물에서 태그를 떼면 page_tags 링크만 지워지고 tags 행은 남는다
 * (pageRepository.update 주석: "고아 tags 행은 무해하다"). 그 줄을 그리면 눌러
 * 봐야 빈 목록인 링크가 목록에 쌓이고, 옛 오타 태그가 영원히 노출된다.
 *
 * **그렇다고 `/tags/[name]` 이 그 태그를 404 로 답하지는 않는다.** 목록에서
 * 빼는 것과 없다고 답하는 것은 다른 판단이다 — 이미 공유된 링크가 "그런 태그
 * 없음"이 되면 사용자는 주소를 잘못 쳤다고 읽는다 (listPagesByTag 주석).
 *
 * 정렬은 **문서 수 내림차순, 같으면 이름순**이다. 이 규칙이 repository 가 아니라
 * 여기 있는 이유는 두 가지다: 화면이 무엇을 먼저 보여줄지는 업무 규칙이고,
 * PostgREST 는 애초에 임베디드 aggregate 로 정렬하지 못한다. 이름 비교에
 * `localeCompare` 를 쓰는 것은 한글 태그가 대부분이라서다 — 코드포인트 순서로는
 * 한글이 사전순으로 정렬되지 않는다.
 *
 * ── 페이지네이션이 없다 ────────────────────────────────────
 * 태그 수만큼의 줄을 한 번에 내린다. 지금은 수십 개 규모라 문제가 없고, 화면도
 * 칩을 흘려 놓는 모양이라 자를 자리가 없다.
 * **다음 조건 중 하나라도 걸리면 그때 페이지네이션(또는 상한)을 넣어라:**
 *   · 태그가 200개를 넘어 한 화면에서 훑는 것이 의미를 잃을 때
 *   · 이 응답이 눈에 띄게 무거워질 때(태그 하나가 이름 + 수 두 칸이라 200개라도
 *     수 KB 지만, 늘어나는 축이 문서 수가 아니라 EDITOR 의 입력이라 상한이 없다)
 * 넣을 때는 정렬 규칙이 이미 전순서라(수 → 이름) offset 페이지네이션이 그대로
 * 성립한다. 목록의 `?page=` 규칙(CLAUDE.md: 무한 스크롤 금지)을 따르면 된다.
 */
export async function listTags(): Promise<TagSummary[]> {
  const tags = await tagRepository.findAll();

  return tags
    .filter((tag) => tag.pageCount > 0)
    .sort(
      (a, b) =>
        b.pageCount - a.pageCount || a.name.localeCompare(b.name, "ko"),
    );
}
