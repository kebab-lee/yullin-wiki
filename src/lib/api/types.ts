/** 실패 응답 바디. 4xx/5xx 는 전부 이 모양이다. */
export type ApiErrorBody = {
  /** 폼 단위로 보여줄 문구. 필드별 문구가 있으면 폼은 그쪽을 우선한다. */
  message: string;
  /** 필드명 → 문구. 검증/중복 실패에만 실린다. */
  fields?: Record<string, string>;
};
