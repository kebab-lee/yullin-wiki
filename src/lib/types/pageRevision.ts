// =============================================================
// page_revisions 도메인 모델
//
// **쓰기 전용 테이블이다.** 조회·복원 UI 는 만들지 않는다 (CLAUDE.md "확정된
// 도메인 결정"). 그래서 읽기용 모델(PageRevision)도 두지 않는다 — 아무도 읽지
// 않는 타입을 미리 만들어 두면 "복원 기능이 있나 보다"라고 읽힌다.
//
// 이 기록의 목적은 되돌리기가 아니라 **추적성**이다. 위키는 공동 편집이라
// 작성자와 무관하게 EDITOR 이상이면 누구나 남의 글을 고친다. 소유권으로 막지
// 않는 대신 "누가 언제 무엇을 덮어썼는가"가 남아야 한다.
// =============================================================

import type { PageContent } from "./page";

/**
 * 수정 "직전" 상태의 스냅샷.
 *
 * 스냅샷 대상이 title / content 뿐인 것은 스키마 그대로다. 카테고리·태그는
 * 남기지 않는다 — 되돌릴 것이 아니라 본문이 어떻게 바뀌었는지를 좇기 위한
 * 기록이고, 컬럼을 늘리면 "복원할 수 있는 것"처럼 보이기 시작한다.
 */
export interface CreatePageRevisionData {
  pageId: string;

  title: string;
  content: PageContent;

  /**
   * 이 스냅샷을 만들어 낸 사람 — 즉 **수정을 실행한 사람**이지 원래 작성자가
   * 아니다. service 가 세션에서 채운다. 입력으로 받지 않는다.
   */
  editedBy: string;
}
