/**
 * 화면 권한 구분.
 * GUEST 는 DB 에 저장되는 값이 아니라 "로그인하지 않은 방문자"를 뜻하는 UI 상태다.
 */
export type Role = "GUEST" | "USER" | "ADMIN";
