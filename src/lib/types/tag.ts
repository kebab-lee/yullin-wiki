// =============================================================
// 태그 도메인 모델
//
// **id 가 없다.** tags 행에는 uuid 가 있지만 화면도 URL(`/tags/[name]`)도
// 이름만 쓰고, 게시물 계약(PageSummary.tags · PageDetail.tags)도 이미 이름
// 배열이다. id 를 여기 실으면 "태그는 uuid 로 식별된다"는 없는 계약이
// 프론트까지 새어나가고, 이름이 unique 인 이상 그 uuid 가 답하는 질문이 없다.
// =============================================================

/**
 * 전체 태그 목록(`/tags`)의 한 줄.
 *
 * pageCount 는 **공개 문서만** 센 수다. 이 목록이 공개 화면이라 DRAFT·HIDDEN·
 * 삭제분을 세면 화면의 수와 클릭해서 보이는 목록의 길이가 어긋난다.
 * (같은 이름의 카테고리 쪽 수 — categoryRepository.countPagesByCategoryId —
 * 는 정반대로 아무것도 거르지 않는다. 그쪽이 답하는 질문이 "이 항목을 지울 수
 * 있는가"이기 때문이며, 두 수는 같은 이름이지만 같은 것이 아니다.)
 */
export type TagSummary = {
  name: string;
  pageCount: number;
};
