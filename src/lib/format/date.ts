// 세 화면(게시물 목록 · 상세 · 어드민 위키 관리)이 같은 함수를 각자 들고 있었다.
// 문자열을 만드는 규칙은 컴포넌트의 사정이 아니라 사이트 전체의 약속이라
// 한곳으로 모은다 — 한쪽만 고쳐지면 같은 값이 화면마다 다른 모양으로 그려진다.
//
// React 를 import 하지 않는 순수 함수다. 서버 컴포넌트와 클라이언트 컴포넌트가
// 함께 쓴다 (검증 모듈과 같은 결).
// =============================================================

/**
 * `2026.08.06` 형태.
 *
 * **timeZone 을 못박는 것이 이 함수의 핵심이다.** 서버와 브라우저의 기본 시간대가
 * 다르면 같은 ISO 값이 서로 다른 날짜로 그려져 hydration 이 어긋난다.
 *
 * Intl 이 `2026. 08. 06.` 을 주므로 끝의 마침표와 공백을 걷어낸다.
 */
export function formatDate(iso: string): string {
  return new Intl.DateTimeFormat("ko-KR", {
    timeZone: "Asia/Seoul",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  })
    .format(new Date(iso))
    .replace(/\.$/, "")
    .replace(/\s/g, "");
}
